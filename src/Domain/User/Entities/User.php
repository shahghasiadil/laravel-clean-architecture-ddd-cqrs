<?php

declare(strict_types=1);

namespace Domain\User\Entities;

use DateTimeImmutable;
use Domain\User\Enums\UserStatus;
use Domain\User\Events\UserRegistered;
use Domain\User\ValueObjects\EmailAddress;
use Domain\User\ValueObjects\HashedPassword;
use Domain\User\ValueObjects\UserId;
use Domain\User\ValueObjects\UserName;
use LogicException;
use Shared\Domain\AggregateRoot;

/**
 * The User aggregate root. This is a plain PHP object with no framework
 * dependency — it owns the business invariants around a user, not the
 * persistence mapping. See Infrastructure\User\Persistence for the Eloquent
 * model and mapper that translate to and from this aggregate.
 */
final class User extends AggregateRoot
{
    private ?UserId $id = null;

    private function __construct(
        private UserName $name,
        private EmailAddress $email,
        private HashedPassword $password,
        private UserStatus $status,
        private readonly ?DateTimeImmutable $createdAt = null,
        private readonly ?DateTimeImmutable $updatedAt = null,
    ) {}

    public static function register(UserName $name, EmailAddress $email, HashedPassword $password): self
    {
        return new self($name, $email, $password, UserStatus::Active);
    }

    public static function reconstitute(
        UserId $id,
        UserName $name,
        EmailAddress $email,
        HashedPassword $password,
        UserStatus $status,
        DateTimeImmutable $createdAt,
        DateTimeImmutable $updatedAt,
    ): self {
        $user = new self($name, $email, $password, $status, $createdAt, $updatedAt);
        $user->id = $id;

        return $user;
    }

    /**
     * Assigns the identity generated by the persistence layer on first
     * insert. This is the point at which the aggregate is considered to
     * exist, so the registration event is recorded here rather than in
     * register() — the id is part of the event's payload.
     */
    public function assignId(UserId $id): void
    {
        if ($this->id instanceof UserId) {
            throw new LogicException('Cannot reassign the id of an existing user.');
        }

        $this->id = $id;
        $this->recordThat(new UserRegistered($id, $this->email));
    }

    public function rename(UserName $name): void
    {
        $this->name = $name;
    }

    public function changeEmail(EmailAddress $email): void
    {
        $this->email = $email;
    }

    public function changePassword(HashedPassword $password): void
    {
        $this->password = $password;
    }

    public function changeStatus(UserStatus $status): void
    {
        $this->status = $status;
    }

    public function hasId(): bool
    {
        return $this->id instanceof UserId;
    }

    public function id(): UserId
    {
        return $this->id ?? throw new LogicException('User has not been persisted yet.');
    }

    public function name(): UserName
    {
        return $this->name;
    }

    public function email(): EmailAddress
    {
        return $this->email;
    }

    public function password(): HashedPassword
    {
        return $this->password;
    }

    public function status(): UserStatus
    {
        return $this->status;
    }

    public function createdAt(): ?DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function updatedAt(): ?DateTimeImmutable
    {
        return $this->updatedAt;
    }
}
